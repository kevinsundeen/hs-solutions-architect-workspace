#!/usr/bin/env python3
"""
Playbooks: a scheduled S2 job as one TOML file instead of a script with its own
install/remove/status, plist writer, env loader and Slack plumbing.

  _meta/playbooks/<name>.toml   the job: schedule + steps
  com.s2.<name>.plist           generated by `sync`; runs `playbook.py run <name>`
  _meta/playbooks/logs/         one log per playbook (gitignored)

Every launchd run goes through job_health.run(), so a playbook gets a heartbeat and shows
in the 07:00 digest footer when it fails or misses a fire, with no extra code.

Format
  description = "one line"
  python = "venv"              # venv (Personal/.venv, default) | system; {python} in steps
  caffeinate = false           # keep the Mac awake for the run
  [schedule]                   # exactly one of:
  every = "5m"                 #   interval: 90s / 5m / 2h
  at = ["06:30", "13:00"]      #   clock times, with optional
  days = "weekdays"            #     daily (default) | weekdays | mon-fri | ["mon", "thu"]
  keep_alive = true            #   long-running service

  [[step]]  run = "{python} _meta/scripts/x.py --flag"   shell, cwd = repo root, .env loaded
  [[step]]  prompt = "..."  model = "claude-haiku-5-5"  headless `claude -p`
  [[step]]  dm = "header\\n{prev}"                     Slack DM to the user
  [[step]]  queue = true                               {prev} is decision JSON → s2 queue create
  Any step: if_output = true (skip when {prev} is empty), timeout = 600 (seconds).
  {prev} is the previous step's stdout, stripped; {root} is the repo root.

CLI (via `s2 playbook`)
  list                       every playbook, schedule, loaded?, last heartbeat
  run <name> [--dry-run]     run now (dry run: show steps, run nothing)
  sync [--dry-run]           write/refresh plists for every playbook; unload removed ones
  new <name>                 scaffold _meta/playbooks/<name>.toml
"""
from __future__ import annotations

import json
import os
import plistlib
import re
import subprocess
import sys
import tomllib
from datetime import datetime
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
QUEUE = SCRIPTS / "decision_queue.py"
REPO_ROOT = SCRIPTS.parents[1]
PLAYBOOK_DIR = REPO_ROOT / "_meta" / "playbooks"
LOG_DIR = PLAYBOOK_DIR / "logs"
AGENTS = Path.home() / "Library" / "LaunchAgents"
PREFIX = "com.s2."
VENV_PY = REPO_ROOT / "Personal" / ".venv" / "bin" / "python3"
SYSTEM_PY = Path("/Library/Frameworks/Python.framework/Versions/3.14/bin/python3")
DAYS = {"sun": 0, "mon": 1, "tue": 2, "wed": 3, "thu": 4, "fri": 5, "sat": 6}
STEP_KINDS = ("run", "prompt", "dm", "queue")
UNIT = {"s": 1, "m": 60, "h": 3600}

sys.path.insert(0, str(SCRIPTS))


class PlaybookError(Exception):
    pass


# ---- load + validate ------------------------------------------------------------------------------
def load(name: str, pdir: Path = PLAYBOOK_DIR) -> dict:
    path = pdir / f"{name}.toml"
    if not path.is_file():
        raise PlaybookError(f"no playbook {path}")
    pb = tomllib.loads(path.read_text(encoding="utf-8"))
    pb["name"] = name
    validate(pb)
    return pb


def names(pdir: Path = PLAYBOOK_DIR) -> list[str]:
    return sorted(p.stem for p in pdir.glob("*.toml")) if pdir.is_dir() else []


def validate(pb: dict) -> None:
    sched = pb.get("schedule") or {}
    modes = [k for k in ("every", "at", "keep_alive") if sched.get(k)]
    if len(modes) != 1:
        raise PlaybookError(f"{pb['name']}: [schedule] needs exactly one of every / at / keep_alive")
    steps = pb.get("step") or []
    if not steps:
        raise PlaybookError(f"{pb['name']}: no [[step]]")
    for i, st in enumerate(steps, 1):
        kinds = [k for k in STEP_KINDS if k in st]
        if len(kinds) != 1:
            raise PlaybookError(f"{pb['name']} step {i}: needs exactly one of {', '.join(STEP_KINDS)}")
    if pb.get("python", "venv") not in ("venv", "system"):
        raise PlaybookError(f"{pb['name']}: python must be venv or system")
    launchd_schedule(sched)          # raises on a bad time / day / interval


# ---- schedule → launchd ---------------------------------------------------------------------------
def parse_interval(text: str) -> int:
    m = re.fullmatch(r"\s*(\d+)\s*([smh])\s*", str(text))
    if not m:
        raise PlaybookError(f"bad interval {text!r} (use 90s / 5m / 2h)")
    return int(m.group(1)) * UNIT[m.group(2)]


def parse_days(days) -> list[int] | None:
    """None means every day."""
    if days in (None, "", "daily"):
        return None
    if days in ("weekdays", "mon-fri"):
        return [1, 2, 3, 4, 5]
    items = [days] if isinstance(days, str) else list(days)
    try:
        return [DAYS[str(d).strip().lower()[:3]] for d in items]
    except KeyError as e:
        raise PlaybookError(f"bad day {e.args[0]!r}") from None


def launchd_schedule(sched: dict) -> dict:
    if sched.get("keep_alive"):
        return {"KeepAlive": True, "RunAtLoad": True}
    if sched.get("every"):
        return {"StartInterval": parse_interval(sched["every"]), "RunAtLoad": False}
    times = sched["at"] if isinstance(sched["at"], list) else [sched["at"]]
    entries = []
    for day in parse_days(sched.get("days")) or [None]:
        for t in times:
            m = re.fullmatch(r"(\d{1,2}):(\d{2})", str(t).strip())
            if not m or int(m.group(1)) > 23 or int(m.group(2)) > 59:
                raise PlaybookError(f"bad time {t!r} (use HH:MM)")
            e = {"Hour": int(m.group(1)), "Minute": int(m.group(2))}
            if day is not None:
                e["Weekday"] = day
            entries.append(e)
    return {"StartCalendarInterval": entries[0] if len(entries) == 1 else entries, "RunAtLoad": False}


def describe(sched: dict) -> str:
    if sched.get("keep_alive"):
        return "always on"
    if sched.get("every"):
        return f"every {sched['every']}"
    times = sched["at"] if isinstance(sched["at"], list) else [sched["at"]]
    days = sched.get("days") or "daily"
    return f"{', '.join(times)} {days if isinstance(days, str) else '/'.join(days)}"


def interpreter(pb: dict) -> str:
    if pb.get("python", "venv") == "venv" and VENV_PY.exists():
        return str(VENV_PY)
    return str(SYSTEM_PY if SYSTEM_PY.exists() else Path(sys.executable))


def plist_for(pb: dict) -> dict:
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    py = interpreter(pb)
    args = [py, str(SCRIPTS / "playbook.py"), "run", pb["name"]]
    if pb.get("caffeinate"):
        args = ["/usr/bin/caffeinate", "-i"] + args
    log = str(LOG_DIR / f"{pb['name']}.log")
    return {
        "Label": PREFIX + pb["name"],
        "ProgramArguments": args,
        **launchd_schedule(pb["schedule"]),
        "EnvironmentVariables": {"PATH": run_path(py)},
        "StandardOutPath": log,
        "StandardErrorPath": log,
    }


def run_path(py: str) -> str:
    return f"{Path.home()}/.local/bin:{Path(py).parent}:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin"


def ours(plist: dict) -> bool:
    """True when this plist was generated by sync, i.e. it is safe to rewrite or remove."""
    return any(str(a).endswith("playbook.py") for a in plist.get("ProgramArguments", []))


# ---- sync -----------------------------------------------------------------------------------------
def sync(dry_run: bool = False, pdir: Path = PLAYBOOK_DIR, agents: Path = AGENTS,
         launchctl=None) -> list[str]:
    launchctl = launchctl or (lambda *a: subprocess.run(["launchctl", *a], capture_output=True))
    out, wanted = [], set()
    for name in names(pdir):
        pb = load(name, pdir)
        wanted.add(name)
        path = agents / f"{PREFIX}{name}.plist"
        new = plist_for(pb)
        if path.is_file():
            cur = plistlib.loads(path.read_bytes())
            if not ours(cur):
                out.append(f"✖ {name}: {path.name} exists and was not made by playbooks; "
                           f"remove it with the old script's `remove` first")
                continue
            if cur == new:
                out.append(f"= {name}: unchanged ({describe(pb['schedule'])})")
                continue
        out.append(f"{'~' if path.is_file() else '+'} {name}: {describe(pb['schedule'])}")
        if not dry_run:
            launchctl("unload", str(path))
            path.write_bytes(plistlib.dumps(new))
            launchctl("load", str(path))
    for path in sorted(agents.glob(f"{PREFIX}*.plist")):
        name = path.stem[len(PREFIX):]
        if name in wanted or not ours(plistlib.loads(path.read_bytes())):
            continue
        out.append(f"- {name}: playbook gone, unloading")
        if not dry_run:
            launchctl("unload", str(path))
            path.unlink()
    if not dry_run:
        try:
            import job_health
            job_health.seed()
        except Exception as e:  # noqa: BLE001 — seeding is a nicety
            out.append(f"⚠ heartbeat seed failed: {e}")
    return out


# ---- run ------------------------------------------------------------------------------------------
def load_env(env: dict) -> dict:
    env = dict(env)
    f = REPO_ROOT / ".env"
    if f.is_file():
        for line in f.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, _, v = line.partition("=")
            k, v = k.removeprefix("export ").strip(), v.strip().strip("'\"")
            if k and k not in env:
                env[k] = v
    return env


def fill(text: str, prev: str, py: str) -> str:
    return text.replace("{prev}", prev).replace("{python}", py).replace("{root}", str(REPO_ROOT))


def slack_dm(text: str, env: dict) -> None:
    import notify
    notify.dm_self(text, env)


def log(name: str, msg: str) -> None:
    print(f"[{datetime.now():%Y-%m-%d %H:%M:%S}] {name}: {msg}", flush=True)


def execute(pb: dict, dry_run: bool = False, env: dict | None = None, dm_fn=slack_dm,
            sh=None) -> int:
    env = load_env(env if env is not None else os.environ)
    py = interpreter(pb)
    env["PATH"] = run_path(py) + ":" + env.get("PATH", "")
    sh = sh or (lambda cmd, timeout, stdin=None: subprocess.run(
        cmd, shell=isinstance(cmd, str), cwd=REPO_ROOT, env=env, input=stdin,
        capture_output=True, text=True, timeout=timeout))
    prev = ""
    for i, st in enumerate(pb["step"], 1):
        kind = next(k for k in STEP_KINDS if k in st)
        if st.get("if_output") and not prev:
            continue
        timeout = st.get("timeout", 600)
        if kind == "run":
            cmd = fill(st["run"], prev, py)
            if dry_run:
                log(pb["name"], f"step {i} would run: {cmd}")
                continue
            r = sh(cmd, timeout)
        elif kind == "prompt":
            cmd = ["claude", "-p", fill(st["prompt"], prev, py)]
            if st.get("model"):
                cmd += ["--model", st["model"]]
            if dry_run:
                log(pb["name"], f"step {i} would prompt claude ({st.get('model') or 'default model'})")
                continue
            r = sh(cmd, timeout)
        elif kind == "dm":
            text = fill(st["dm"], prev, py)
            if dry_run:
                log(pb["name"], f"step {i} would DM:\n{text}")
                continue
            dm_fn(text, env)
            log(pb["name"], f"step {i} DM sent ({len(text)} chars)")
            continue
        else:  # queue
            if not QUEUE.is_file():
                log(pb["name"], f"step {i} queue skipped: {QUEUE.name} not installed")
                continue
            if dry_run:
                log(pb["name"], f"step {i} would queue a decision from the previous output")
                continue
            r = sh([py, str(QUEUE), "create", "--stdin"], timeout, stdin=prev)
        if r.returncode != 0:
            err = (r.stderr or r.stdout or "").strip()[-500:]
            log(pb["name"], f"step {i} ({kind}) exited {r.returncode}: {err}")
            return r.returncode
        prev = (r.stdout or "").strip()
        if r.stderr and r.stderr.strip():
            log(pb["name"], f"step {i} stderr: {r.stderr.strip()[-300:]}")
    return 0


# ---- CLI ------------------------------------------------------------------------------------------
TEMPLATE = '''description = "What this does, in one line"
python = "venv"

[schedule]
at = ["07:00"]
days = "weekdays"

[[step]]
run = "{python} _meta/scripts/your-script.py"

[[step]]
dm = "{prev}"
if_output = true
'''


def cmd_list() -> int:
    loaded = subprocess.run(["launchctl", "list"], capture_output=True, text=True).stdout
    hb_dir = REPO_ROOT / "_meta" / "queue" / "heartbeats"
    rows = names()
    for name in rows:
        try:
            pb = load(name)
            sched = describe(pb["schedule"])
        except (PlaybookError, tomllib.TOMLDecodeError) as e:
            print(f"✖ {name}: {e}")
            continue
        hb_file = hb_dir / f"{name}.json"
        hb = json.loads(hb_file.read_text()) if hb_file.is_file() else {}
        last = ("✖ " + hb["last_error_at"][:16]) if hb.get("last_error_at", "") > hb.get("last_ok", "") \
            else (hb.get("last_ok", "")[:16] or "never")
        state = "loaded" if f"\t{PREFIX}{name}" in loaded else "NOT LOADED"
        print(f"{name:<20} {sched:<28} {state:<11} last run {last}  — {pb.get('description', '')}")
    if not rows:
        print(f"no playbooks in {PLAYBOOK_DIR}")
    return 0


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "list"
    rest = argv[1:]
    try:
        if cmd == "list":
            return cmd_list()
        if cmd == "sync":
            print("\n".join(sync(dry_run="--dry-run" in rest)) or "no playbooks")
            return 0
        if cmd == "run" and rest:
            pb = load(rest[0])
            import job_health
            return job_health.run(pb["name"], execute, pb, "--dry-run" in rest) or 0
        if cmd == "new" and rest:
            path = PLAYBOOK_DIR / f"{rest[0]}.toml"
            if path.exists():
                raise PlaybookError(f"{path} already exists")
            PLAYBOOK_DIR.mkdir(parents=True, exist_ok=True)
            path.write_text(TEMPLATE, encoding="utf-8")
            print(f"Wrote {path}\nEdit it, then: s2 playbook sync")
            return 0
    except (PlaybookError, tomllib.TOMLDecodeError) as e:
        print(f"playbook: {e}", file=sys.stderr)
        return 2
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
